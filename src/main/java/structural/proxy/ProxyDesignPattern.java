package structural.proxy;

public class ProxyDesignPattern {
    public static void main(String[] args) {
        /**
         *  Proxy is a structural design pattern that lets you provide a substitute
         *  or placeholder i.e Proxy for another object.
         *
         *  ** Access control
         *  A proxy controls access to the original object, allowing you to perform
         *  something either before or after the request gets through to the original object.

         *  Real World Analogy :

         *  A credit card is a proxy for a bank account, which is a proxy for a bundle of cash.
         *  Both implement the same interface: they can be used for making a payment.
         *  A consumer feels great because there’s no need to carry loads of cash around.
         *  A shop owner is also happy since the income from a transaction gets added electronically
         *  to the shop’s bank account without the risk of losing the deposit or getting robbed on the
         *  way to the bank.
         */
    }
}
